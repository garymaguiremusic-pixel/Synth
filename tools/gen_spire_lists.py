"""Extracts Spire's list entries (names per stored index, index = round(value * 999)) from a vc_probe
spire_params.json and writes Engine/SpireLists.h. Only the plugin's own parameter display text is used."""
import json, sys

def main(src, out_json, out_h):
    params = {p['name']: p for p in json.load(open(src, encoding='utf-8'))['params']}
    want = {'targets': 'env1_target1', 'sources': 'slot1_Src1', 'waves': 'osc1_wave', 'lfoForms': 'lfo1_form',
            'oscTypes': 'osc1_type', 'filterTypes': 'flt1_type', 'filterModes': 'flt1_mode', 'arpSpeeds': 'arp_speed',
            'arpModes': 'arp_mode', 'voiceModes': 'mode', 'unisonCounts': 'osc1_ucnt', 'unisonModes': 'osc1_uoct'}
    lists = {}
    for key, name in want.items():
        entries = [t for k, t in params[name]['changes']]
        while entries and entries[-1].strip() in ('', '-'):
            entries.pop()
        lists[key] = [e.strip() for e in entries]
    json.dump(lists, open(out_json, 'w'), indent=1)
    with open(out_h, 'w') as f:
        f.write('#pragma once\n// Generated by tools/gen_spire_lists.py from the user\'s Spire (vc_probe): list entry names per\n')
        f.write('// stored index (value = index / 999). Do not edit.\n\nnamespace vc::spire::lists\n{\n')
        for key, entries in lists.items():
            f.write(f'    inline constexpr const char* {key}[] = {{ ' + ', '.join(json.dumps(e) for e in entries) + ' };\n')
            f.write(f'    inline constexpr int {key}Count = {len(entries)};\n')
        f.write('}\n')

if __name__ == '__main__':
    main(*sys.argv[1:4])
