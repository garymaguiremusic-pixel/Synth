#!/usr/bin/env python3
"""reference/spire_param_map.csv -> SpireLayout.h (725 normalised parameters: key, list flag, init value)."""
import csv, os, re, sys

def ident(k):
    s = re.sub(r'[^A-Za-z0-9]+', '_', k.replace('(inferred)', '')).strip('_')
    return 'P_' + s if s[0].isdigit() else s

src, out = sys.argv[1:3]
rows = list(csv.DictReader(open(src, encoding='utf-8-sig')))
assert len(rows) == 725
o = ['// GENERATED by tools/gen_spire_layout.py from reference/spire_param_map.csv - do not edit.', '#pragma once',
     '#include <string_view>', '', 'namespace vc::spire', '{',
     'struct ParamDef { int index; const char* key; bool discrete; float init; };',
     'inline constexpr int kNumParams = 725;', 'inline constexpr ParamDef kParams[kNumParams] = {']
for r in rows:
    key = r['key'].replace('(inferred)', '')
    o.append('    { %s, "%s", %s, %sf },' % (r['index'], key, 'true' if r['discrete_1000'] == 'yes' else 'false',
                                           repr(float(r['init_value']))))
o += ['};', '', 'namespace idx', '{']
seen = set()
for r in rows:
    i = ident(r['key'])
    if i in seen:
        i += '_' + r['index']
    seen.add(i)
    o.append('    inline constexpr int %s = %s;' % (i, r['index']))
o += ['}', '', 'inline int findParam (std::string_view key)', '{',
      '    for (const auto& p : kParams) if (key == p.key) return p.index;', '    return -1;', '}', '} // namespace vc::spire', '']
os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
text = '\n'.join(o)
if not (os.path.exists(out) and open(out).read() == text):
    open(out, 'w', newline='\n').write(text)
