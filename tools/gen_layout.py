#!/usr/bin/env python3
"""
Generates VirusCLayout.h from the reference data:

  reference/virusC_single_256byte_map.csv      (offset, name, min, max, default, toText)
  reference/osirus_parameterDescriptions.json  (value lists, regions, controller map,
                                                and the ranges the CSV leaves empty)

Usage: gen_layout.py <csv> <json> <out.h>

Pure standard library, so it runs on any build machine with Python 3.
"""
import csv
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lenient_json  # noqa: E402


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def ident(name):
    out = []
    for ch in name.strip():
        out.append(ch if ch.isalnum() else '_')
    s = ''.join(out)
    while '__' in s:
        s = s.replace('__', '_')
    s = s.strip('_')
    if not s or s[0].isdigit():
        s = 'P_' + s
    return s


def main():
    csv_path, json_path, out_path = sys.argv[1:4]
    rows = list(csv.DictReader(open(csv_path, encoding='utf-8-sig')))
    desc = lenient_json.load(json_path)

    by_name = {}
    for d in desc['parameterdescriptions']:
        if d.get('page') in (112, 113) and d['name'] not in by_name:
            by_name[d['name']] = d

    valuelists = desc['valuelists']
    params = []
    for r in rows:
        off = int(r['offset'])
        name = (r['name'] or '').strip()
        dn = (r.get('displayName') or '').strip()
        mn, mx, df, tt, pub = r['min'], r['max'], r['default'], r['toText'], r['isPublic']
        source = 'csv'
        if name and (mn == '' or mx == ''):
            j = by_name.get(r['name']) or by_name.get(name)
            if j:
                mn = str(j.get('min', 0))
                mx = str(j.get('max', 127))
                tt = tt or j.get('toText', '')
                pub = 'true' if j.get('isPublic', True) else 'false'
                source = 'json'
        if not name:
            name = 'Unused%d' % off
        if mn == '':
            mn = '0'
        if mx == '':
            mx = '127'
        mn, mx = int(mn), int(mx)
        if df == '':
            df = mn
        df = max(mn, min(mx, int(df)))
        if tt and tt not in valuelists:
            print('warning: toText %r for %r has no value list' % (tt, name), file=sys.stderr)
        is_public = (pub or '').lower() == 'true'
        if name.startswith(('A_Undefined', 'B_Undefined', 'Unused')):
            is_public = False
        params.append(dict(offset=off, name=name, display=dn or name, min=mn, max=mx,
                           default=df, toText=tt or '', public=is_public, source=source))

    assert len(params) == 256 and all(p['offset'] == i for i, p in enumerate(params)), 'CSV must hold 256 rows in order'

    name_to_off = {}
    for p in params:
        name_to_off.setdefault(p['name'], p['offset'])
        name_to_off.setdefault(p['name'].strip(), p['offset'])

    # value lists used by the CSV, plus the ones the engine/UI need by name
    wanted = sorted({p['toText'] for p in params if p['toText']} |
                    {'delayReverbMode', 'reverbRoomSize', 'delayLfoShape', 'bpm', 'category'})

    # aliases: JSON names that share a byte with a CSV name (e.g. "Rev Size" = "Dly Depth")
    for d in desc['parameterdescriptions']:
        if d.get('page') in (112, 113):
            name_to_off.setdefault(d['name'], d['index'] + (0 if d['page'] == 112 else 128))

    reg_by_id = {r['id']: r for r in desc['regions']}

    def region_offsets(reg):
        offs = []
        for n in reg.get('parameters', []):
            o = name_to_off.get(n, name_to_off.get(n.strip()))
            if o is not None and o not in offs:
                offs.append(o)
        for child in reg.get('regions', []):
            for o in region_offsets(reg_by_id[child]):
                if o not in offs:
                    offs.append(o)
        return offs

    regions = [(reg['id'], reg['name'], region_offsets(reg)) for reg in desc['regions']]

    ccmap = []
    for c in desc.get('controllerMap', []):
        n = c.get('param', '')
        if n not in name_to_off:
            continue
        if 'cc' in c:
            ccmap.append(('CC', c['cc'], name_to_off[n]))
        elif 'pp' in c:
            ccmap.append(('PolyPressure', c['pp'], name_to_off[n]))

    o = []
    o.append('// GENERATED by tools/gen_layout.py from reference/ - do not edit.')
    o.append('// Source data: Gearmulator (GPL-3) parameter descriptions for the Virus A/B/C.')
    o.append('#pragma once')
    o.append('#include <cstdint>')
    o.append('#include <string_view>')
    o.append('')
    o.append('namespace vc::layout')
    o.append('{')
    o.append('struct ValueList { const char* name; const char* const* items; int count; };')
    o.append('')
    for vl in wanted:
        items = valuelists[vl]
        o.append('inline constexpr const char* kVL_%s[] = { %s };' % (ident(vl), ', '.join(cstr(str(x)) for x in items)))
    o.append('')
    o.append('inline constexpr ValueList kValueLists[] = {')
    for vl in wanted:
        o.append('    { %s, kVL_%s, %d },' % (cstr(vl), ident(vl), len(valuelists[vl])))
    o.append('};')
    o.append('inline constexpr int kNumValueLists = %d;' % len(wanted))
    o.append('')
    o.append('struct ParamDef')
    o.append('{')
    o.append('    int offset;            // byte offset in the 256-byte single (0-127 = page A, 128-255 = page B)')
    o.append('    const char* name;      // name as in the CSV / Osirus JSON')
    o.append('    const char* id;        // identifier-safe name (plugin parameter ID)')
    o.append('    int min, max, def;')
    o.append('    const char* toText;    // value list name, "" = plain number')
    o.append('    bool isPublic;')
    o.append('};')
    o.append('')
    o.append('inline constexpr ParamDef kParams[256] = {')
    for p in params:
        o.append('    { %3d, %-28s %-28s %3d, %3d, %3d, %-22s %s },' % (
            p['offset'], cstr(p['name']) + ',', cstr(ident(p['name'])) + ',', p['min'], p['max'], p['default'],
            cstr(p['toText']) + ',', 'true' if p['public'] else 'false'))
    o.append('};')
    o.append('')
    o.append('// Named offsets')
    o.append('namespace off')
    o.append('{')
    seen = set()
    for p in params:
        i = ident(p['name'])
        if i in seen:
            i = '%s_%d' % (i, p['offset'])
        seen.add(i)
        o.append('    inline constexpr int %s = %d;' % (i, p['offset']))
    o.append('}')
    o.append('')
    o.append('struct Region { const char* id; const char* name; const int* offsets; int count; };')
    for rid, rname, offs in regions:
        o.append('inline constexpr int kRegion_%s[] = { %s };' % (ident(rid), ', '.join(str(x) for x in offs) if offs else '-1'))
    o.append('inline constexpr Region kRegions[] = {')
    for rid, rname, offs in regions:
        o.append('    { %s, %s, kRegion_%s, %d },' % (cstr(rid), cstr(rname), ident(rid), len(offs)))
    o.append('};')
    o.append('inline constexpr int kNumRegions = %d;' % len(regions))
    o.append('')
    o.append('enum class CtlType { CC, PolyPressure };')
    o.append('struct ControllerMapEntry { CtlType type; int number; int offset; };')
    o.append('inline constexpr ControllerMapEntry kControllerMap[] = {')
    for t, num, off in ccmap:
        o.append('    { CtlType::%s, %d, %d },' % (t, num, off))
    o.append('};')
    o.append('inline constexpr int kControllerMapSize = %d;' % len(ccmap))
    o.append('')
    o.append('inline const ValueList* findValueList (std::string_view name)')
    o.append('{')
    o.append('    for (const auto& v : kValueLists)')
    o.append('        if (name == v.name) return &v;')
    o.append('    return nullptr;')
    o.append('}')
    o.append('')
    o.append('inline int findParam (std::string_view name)')
    o.append('{')
    o.append('    for (const auto& p : kParams)')
    o.append('        if (name == p.name || name == p.id) return p.offset;')
    o.append('    return -1;')
    o.append('}')
    o.append('} // namespace vc::layout')
    o.append('')

    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    text = '\n'.join(o)
    if os.path.exists(out_path) and open(out_path, encoding='utf-8').read() == text:
        return
    with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


if __name__ == '__main__':
    main()
